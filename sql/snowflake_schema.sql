-- 1. WAREHOUSE & DATABASE INITIALIZATION
USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS ATMOSYNC_WH
    WITH WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    MIN_CLUSTER_COUNT = 1
    MAX_CLUSTER_COUNT = 2
    SCALING_POLICY = 'ECONOMY'
    COMMENT = 'Virtual warehouse for high-throughput IoT container stream ingestion and dbt ELT modeling';

CREATE DATABASE IF NOT EXISTS ATMOSYNC_DWH
    COMMENT = 'Enterprise Cloud Data Warehouse for AtmoSync Micro-Climate Analytics';

USE DATABASE ATMOSYNC_DWH;

-- 2. SCHEMA DEFINITIONS (MDS 3-LAYER ARCHITECTURE)
CREATE SCHEMA IF NOT EXISTS RAW
    COMMENT = 'Bronze Layer: Raw semi-structured JSON telemetry from Apache Kafka / Snowpipe';

CREATE SCHEMA IF NOT EXISTS STAGING
    COMMENT = 'Silver Layer: Cleaned, type-cast, and deduplicated container views generated by dbt';

CREATE SCHEMA IF NOT EXISTS MARTS
    COMMENT = 'Gold Layer: Dimensional star-schema and Spoilage Arbitrage fact tables for BI layer';

-- 3. FILE FORMATS & STAGES
USE SCHEMA RAW;

CREATE OR REPLACE FILE FORMAT FF_JSON_STREAMING
    TYPE = 'JSON'
    COMPRESSION = 'AUTO'
    ENABLE_OCTAL = FALSE
    ALLOW_DUPLICATE = FALSE
    STRIP_OUTER_ARRAY = TRUE
    IGNORE_UTF8_ERRORS = FALSE
    COMMENT = 'JSON file format for streaming Kafka IoT container packets';

-- Simulated cloud stage for streaming telemetry payloads
CREATE OR REPLACE STAGE STG_KAFKA_IOT_STREAM
    FILE_FORMAT = FF_JSON_STREAMING
    COMMENT = 'Internal landing stage buffering Kafka event batches prior to Snowpipe loading';

-- 4. BRONZE LAYER: RAW STREAMING INGESTION TABLE
CREATE OR REPLACE TABLE RAW_CONTAINER_IOT_STREAM (
    STREAM_ID           VARCHAR(64) DEFAULT UUID_STRING(),
    INGESTED_AT         TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    KAFKA_TOPIC         VARCHAR(128) DEFAULT 'container-telemetry-stream',
    KAFKA_PARTITION     NUMBER(4,0) DEFAULT 0,
    KAFKA_OFFSET        NUMBER(18,0),
    RAW_PAYLOAD         VARIANT NOT NULL,
    CONSTRAINT PK_RAW_STREAM PRIMARY KEY (STREAM_ID)
)
CLUSTER BY (TO_DATE(INGESTED_AT), KAFKA_TOPIC)
COMMENT = 'Landing table for high-throughput raw IoT container payloads';

-- 5. SNOWPIPE CONTINUOUS INGESTION PIPE
CREATE OR REPLACE PIPE PIPE_KAFKA_IOT_INGEST
    AUTO_INGEST = TRUE
    COMMENT = 'Automated continuous ingestion pipe loading Kafka S3/Blob micro-batches into raw landing table'
AS
COPY INTO RAW_CONTAINER_IOT_STREAM (RAW_PAYLOAD, KAFKA_OFFSET)
FROM (
    SELECT
        $1 AS RAW_PAYLOAD,
        METADATA$FILE_ROW_NUMBER AS KAFKA_OFFSET
    FROM @STG_KAFKA_IOT_STREAM
);

-- 6. SILVER LAYER: VIEW NORMALIZING RAW JSON PAYLOADS
USE SCHEMA STAGING;

CREATE OR REPLACE VIEW V_CONTAINER_TELEMETRY_NORM AS
SELECT
    RAW_PAYLOAD:container_id::STRING                AS CONTAINER_ID,
    RAW_PAYLOAD:timestamp::TIMESTAMP_NTZ            AS MEASURED_AT,
    RAW_PAYLOAD:commodity::STRING                   AS COMMODITY,
    RAW_PAYLOAD:cargo_tonnage::FLOAT                AS CARGO_TONNAGE,
    RAW_PAYLOAD:cargo_value_usd::FLOAT              AS CARGO_VALUE_USD,
    RAW_PAYLOAD:origin::STRING                      AS ORIGIN_HUB,
    RAW_PAYLOAD:primary_destination::STRING         AS PRIMARY_DESTINATION,
    RAW_PAYLOAD:secondary_destination::STRING       AS SECONDARY_DESTINATION,
    RAW_PAYLOAD:current_latitude::FLOAT             AS CURRENT_LAT,
    RAW_PAYLOAD:current_longitude::FLOAT            AS CURRENT_LON,
    RAW_PAYLOAD:internal_temp_celsius::FLOAT        AS INTERNAL_TEMP_CELSIUS,
    RAW_PAYLOAD:internal_humidity_percent::FLOAT    AS INTERNAL_HUMIDITY_PERCENT,
    RAW_PAYLOAD:vibration_g::FLOAT                  AS VIBRATION_G,
    RAW_PAYLOAD:reefer_telemetry_status::STRING     AS REEFER_STATUS,
    RAW_PAYLOAD:hours_to_primary_market::FLOAT      AS HOURS_TO_PRIMARY,
    RAW_PAYLOAD:hours_to_secondary_market::FLOAT    AS HOURS_TO_SECONDARY,
    RAW_PAYLOAD:dist_to_secondary_km::FLOAT         AS DIST_TO_SECONDARY_KM,
    INGESTED_AT                                     AS DWH_LOADED_AT
FROM ATMOSYNC_DWH.RAW.RAW_CONTAINER_IOT_STREAM;

-- 7. ROLE-BASED ACCESS CONTROL (RBAC) & PERMISSIONS
USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS DATA_ENGINEER_ROLE COMMENT = 'Full DDL/DML access to pipeline models and Snowflake stages';
